-- The genesis schema. It makes the choices a small startup really makes; each one works at low
-- load and becomes the reason for a later move (plan: "Seeds of pain").
--
-- One deliberate concession: tenant-scoped tables carry seller_id in their primary key from the
-- start, so sharding by seller stays possible later without rekeying the schema.
--
-- Every statement the API runs is tagged with a /*gp:<class>:<name>*/ comment, which
-- pg_stat_statements keeps, so the agent can class database time as reads or writes.

CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
-- Search starts with an index: rare terms, typos, and three-character typing prefixes must
-- not scan the entire catalog while a fractional CPU quota is busy with listing sorts.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE categories (
    category_id integer PRIMARY KEY,
    slug        text NOT NULL UNIQUE,
    name        text NOT NULL
);

CREATE TABLE sellers (
    seller_id  bigint PRIMARY KEY,
    name       text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
-- Sellers who sign up during a run number from here, above every base seller.
CREATE SEQUENCE seller_seq START 100000;

-- product_id = seller_id * 1,000,000 + n, so every product URL names its seller.
CREATE TABLE products (
    seller_id           bigint NOT NULL REFERENCES sellers ON DELETE CASCADE,
    product_id          bigint NOT NULL,
    category_id         integer NOT NULL REFERENCES categories,
    title               text NOT NULL,
    description         text NOT NULL,
    description_version integer NOT NULL DEFAULT 1,
    price_cents         integer NOT NULL,
    image_key           text,
    thumbnail_key       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (seller_id, product_id)
);
CREATE INDEX products_category ON products (category_id, created_at DESC);
-- For the listing's price sorts and price facets.
CREATE INDEX products_category_price ON products (category_id, price_cents);
CREATE INDEX products_created ON products (created_at DESC);
CREATE INDEX products_title_trgm ON products USING gin (title gin_trgm_ops);
CREATE INDEX products_description_trgm ON products USING gin (description gin_trgm_ops);

-- New products take their number within the seller from here, above every base product.
CREATE SEQUENCE product_local_seq START 500000 MAXVALUE 999999;

CREATE TABLE variants (
    seller_id   bigint NOT NULL,
    variant_id  bigint NOT NULL,
    product_id  bigint NOT NULL,
    sku         text NOT NULL,
    options     jsonb NOT NULL,
    price_cents integer NOT NULL,
    stock       integer NOT NULL CHECK (stock >= 0),
    PRIMARY KEY (seller_id, variant_id),
    FOREIGN KEY (seller_id, product_id) REFERENCES products ON DELETE CASCADE
);
CREATE INDEX variants_product ON variants (seller_id, product_id);

CREATE TABLE reviews (
    seller_id  bigint NOT NULL,
    review_id  bigint GENERATED BY DEFAULT AS IDENTITY,
    product_id bigint NOT NULL,
    user_id    bigint NOT NULL,
    rating     smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body       text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (seller_id, review_id),
    FOREIGN KEY (seller_id, product_id) REFERENCES products ON DELETE CASCADE
);
CREATE INDEX reviews_product ON reviews (seller_id, product_id, created_at DESC);

-- Images live in the database at genesis: originals and thumbnails as bytea.
CREATE TABLE images (
    seller_id    bigint NOT NULL,
    image_key    text NOT NULL,
    product_id   bigint NOT NULL,
    kind         text NOT NULL CHECK (kind IN ('original', 'thumbnail')),
    content_type text NOT NULL,
    bytes        bytea NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (seller_id, image_key),
    FOREIGN KEY (seller_id, product_id) REFERENCES products ON DELETE CASCADE
);

CREATE TABLE followers (
    seller_id   bigint NOT NULL REFERENCES sellers ON DELETE CASCADE,
    follower_id bigint NOT NULL,
    PRIMARY KEY (seller_id, follower_id)
);

-- Written synchronously, one row per follower, inside the request that creates a product.
CREATE TABLE notifications (
    notification_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    follower_id     bigint NOT NULL,
    seller_id       bigint NOT NULL,
    product_id      bigint NOT NULL,
    message         text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- Orders are per seller, like a marketplace's per-shop orders. They keep their history when a
-- product is deleted, so they have no foreign key to variants.
CREATE TABLE orders (
    seller_id   bigint NOT NULL,
    order_id    bigint GENERATED BY DEFAULT AS IDENTITY,
    buyer_id    bigint NOT NULL,
    total_cents bigint NOT NULL,
    line_count  integer NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (seller_id, order_id)
);

CREATE TABLE order_items (
    seller_id   bigint NOT NULL,
    order_id    bigint NOT NULL,
    line_no     integer NOT NULL,
    variant_id  bigint NOT NULL,
    quantity    integer NOT NULL,
    price_cents integer NOT NULL,
    PRIMARY KEY (seller_id, order_id, line_no),
    FOREIGN KEY (seller_id, order_id) REFERENCES orders ON DELETE CASCADE
);

CREATE TABLE reservations (
    seller_id  bigint NOT NULL,
    order_id   bigint NOT NULL,
    variant_id bigint NOT NULL,
    quantity   integer NOT NULL,
    expires_at timestamptz NOT NULL,
    PRIMARY KEY (seller_id, order_id, variant_id),
    FOREIGN KEY (seller_id, order_id) REFERENCES orders ON DELETE CASCADE
);

-- Idempotency keys on writes, kept for ten minutes, so a client can retry across a cutover.
CREATE TABLE idempotency_keys (
    idem_key   text PRIMARY KEY,
    route      text NOT NULL,
    status     integer NOT NULL,
    body       bytea NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idempotency_created ON idempotency_keys (created_at);
